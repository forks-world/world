/// Apply one sequence of `COp`s to both the model and a real scratch
/// directory, asserting agreement after every op (so a divergence is
/// reported against the exact minimal op that caused it, not just the whole
/// sequence).
fn run_case(seed: u64) {
    let ops = gen_ops(&mut Rng::new(seed), OPS_PER_CASE);
    let scratch = make_scratch_dir(&seed.to_string());
    let anchor = scratch.as_os_str().as_bytes().to_vec();
    let mut model = Model::new_plain(&anchor);
    let mut real_files: HashMap<u32, File> = HashMap::new();
    let mut id_to_model_fd: HashMap<u32, u32> = HashMap::new();
    let mut harness_errors: Vec<String> = Vec::new();

    // SAFETY: opening a directory we just created/canonicalized ourselves.
    let dirfd = {
        let c = CString::new(scratch.as_os_str().as_bytes()).expect("scratch path has no NUL");
        let fd = unsafe {
            libc::open(
                c.as_ptr(),
                libc::O_RDONLY | libc::O_DIRECTORY | libc::O_CLOEXEC,
            )
        };
        assert!(
            fd >= 0,
            "open scratch dirfd: {}",
            io::Error::last_os_error()
        );
        unsafe { OwnedFd::from_raw_fd(fd) }
    };

    for (i, cop) in ops.iter().enumerate() {
        let Some(real_out) = run_real(&scratch, dirfd.as_raw_fd(), cop, &mut real_files) else {
            harness_errors.push(format!("op {i} {cop:?}: guard rejected operand; skipped"));
            continue;
        };
        let model_out = model.apply(&to_model_op(cop, &id_to_model_fd));

        if let (COp::Create { id, .. }, 0) = (cop, model_out.errno) {
            id_to_model_fd.insert(*id, model_out.ret as u32);
        }

        let linux = cfg!(target_os = "linux");
        assert!(
            errno_equiv(linux, model_out.errno, real_out.errno),
            "case {seed} op {i} {cop:?}: errno mismatch model={} real={}",
            model_out.errno,
            real_out.errno
        );
        if model_out.errno == 0 {
            assert_eq!(
                model_out.ret >= 0,
                real_out.ret >= 0,
                "case {seed} op {i} {cop:?}: ret sign mismatch model={} real={}",
                model_out.ret,
                real_out.ret
            );
            match cop {
                COp::Read { .. } | COp::Readlink(_) | COp::List(_) => {
                    assert_eq!(
                        model_out.data, real_out.data,
                        "case {seed} op {i} {cop:?}: data mismatch"
                    );
                }
                COp::Stat(_) | COp::Lstat(_) => {
                    assert_eq!(
                        model_out.data.first(),
                        real_out.data.first(),
                        "case {seed} op {i} {cop:?}: stat kind mismatch"
                    );
                }
                _ => {}
            }
        }
    }
    assert!(
        harness_errors.is_empty(),
        "case {seed}: harness rejected operands: {harness_errors:?}"
    );
    drop(dirfd);
    cleanup(&scratch);
}

#[test]
fn model_agrees_with_the_real_kernel_on_random_op_sequences() {
    if let Err(msg) =
        ensure_sandboxed_or_reexec("model_agrees_with_the_real_kernel_on_random_op_sequences")
    {
        eprintln!(
            "SKIPPING model_agrees_with_the_real_kernel_on_random_op_sequences: {msg} \
             (refusing to run real, mutating filesystem ops unsandboxed)"
        );
        return;
    }
    for case in 0..case_count() {
        run_case(0xC0FF_EE00 + case as u64);
    }
}

/// Demonstrates that the sandbox guard actually rejects an escaping operand
/// rather than ever executing it: a `Rename` whose `to` climbs out of the
/// scratch directory must be refused by [`guard`] (via [`run_real`]
/// returning `None`), and the escaping path must never be created.
#[test]
fn guard_rejects_escaping_rename() {
    let scratch = make_scratch_dir("guard-demo");
    let dirfd = {
        let c = CString::new(scratch.as_os_str().as_bytes()).unwrap();
        let fd = unsafe {
            libc::open(
                c.as_ptr(),
                libc::O_RDONLY | libc::O_DIRECTORY | libc::O_CLOEXEC,
            )
        };
        assert!(fd >= 0);
        unsafe { OwnedFd::from_raw_fd(fd) }
    };

    // A real file to (attempt to) rename.
    mkdirat_raw(dirfd.as_raw_fd(), "src", 0o755).unwrap();

    let mut files = HashMap::new();
    let escaping = COp::Rename {
        from: "src".to_string(),
        to: "../../escape".to_string(),
    };
    let result = run_real(&scratch, dirfd.as_raw_fd(), &escaping, &mut files);
    assert!(
        result.is_none(),
        "guard should have rejected the escaping rename, got {result:?}"
    );

    // The escaping target must not exist anywhere near the scratch parent.
    if let Some(parent) = scratch.parent().and_then(|p| p.parent()) {
        assert!(
            !parent.join("escape").exists(),
            "escaping rename target was actually created!"
        );
    }
    // And the original file must be untouched (rename never ran).
    assert!(
        fstatat_raw(dirfd.as_raw_fd(), "src", 0).is_ok(),
        "source should be untouched"
    );

    drop(dirfd);
    cleanup(&scratch);
}

/// The guard must also reject a plain `..`/`.`/empty operand and an operand
/// containing an embedded `/`, independent of any real filesystem state.
#[test]
fn guard_rejects_dotdot_dot_and_embedded_slash() {
    let scratch = make_scratch_dir("guard-demo2");
    let dirfd = {
        let c = CString::new(scratch.as_os_str().as_bytes()).unwrap();
        let fd = unsafe {
            libc::open(
                c.as_ptr(),
                libc::O_RDONLY | libc::O_DIRECTORY | libc::O_CLOEXEC,
            )
        };
        assert!(fd >= 0);
        unsafe { OwnedFd::from_raw_fd(fd) }
    };
    for bad in ["..", ".", "", "a/b", "../escape"] {
        assert!(
            guard(&scratch, dirfd.as_raw_fd(), bad).is_err(),
            "guard should reject operand {bad:?}"
        );
    }
    drop(dirfd);
    cleanup(&scratch);
}
