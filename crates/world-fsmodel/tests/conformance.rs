fn base_dir() -> PathBuf {
    std::env::var_os("CARGO_TARGET_TMPDIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../target/fsmodel-conformance")
        })
}

/// Create (or recreate) `base_dir()/case-<tag>-<pid>` and return its
/// *canonical* path.
fn make_scratch_dir(tag: &str) -> PathBuf {
    let base = base_dir();
    std::fs::create_dir_all(&base).expect("create conformance base dir");
    let pid = std::process::id();
    let dir = base.join(format!("case-{tag}-{pid}"));
    if dir.exists() {
        std::fs::remove_dir_all(&dir).ok();
    }
    std::fs::create_dir_all(&dir).expect("create case scratch dir");
    std::fs::canonicalize(&dir).expect("canonicalize scratch dir")
}

/// Cleanup guard (item 4): only ever `remove_dir_all` a path that is
/// unmistakably one of ours.
fn cleanup(scratch: &Path) {
    let text = scratch.to_string_lossy();
    assert!(
        text.contains("fsmodel-conformance") && text.contains("case-"),
        "refusing to remove_dir_all a path outside the expected scratch tree: {text}"
    );
    let _ = std::fs::remove_dir_all(scratch);
}

